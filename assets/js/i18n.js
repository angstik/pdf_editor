let LANG = 'en';

function detectLang(){
  const saved = localStorage.getItem('pdfed.lang');
  if(saved && I18N[saved]) return saved;
  for(const nav of (navigator.languages || [navigator.language || 'en'])){
    const code = String(nav).slice(0,2).toLowerCase();
    if(I18N[code]) return code;
  }
  return 'en';
}

/* t('t.imagesAdded', {n:3}) — les clés manquantes retombent sur l'anglais */
function t(key, vars){
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
  if(vars) for(const k in vars) s = s.split('{'+k+'}').join(vars[k]);
  return s;
}
const locale = ()=> (I18N[LANG] && I18N[LANG].locale) || 'en-GB';

/* Applique les traductions au balisage statique :
   data-i18n -> textContent, data-i18n-title -> title + aria-label,
   data-i18n-ph -> placeholder */
function applyI18n(root=document){
  root.querySelectorAll('[data-i18n]').forEach(el=>{ el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach(el=>{
    const v = t(el.dataset.i18nTitle);
    el.title = v;
    if(el.hasAttribute('aria-label') || el.classList.contains('icon')) el.setAttribute('aria-label', v);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach(el=>{ el.placeholder = t(el.dataset.i18nPh); });
  document.documentElement.lang = LANG;
}

function setLang(code){
  if(!I18N[code]) return;
  LANG = code;
  localStorage.setItem('pdfed.lang', code);
  applyI18n();
  if(typeof onLangChange === 'function') onLangChange();
}

